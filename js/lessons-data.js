export function getLessonById(id) {
  return LESSONS.find(l => l.id === id);
}

export function getLessonsByTier() {
  const tiers = {};
  for (const lesson of LESSONS) {
    if (!tiers[lesson.tier]) {
      tiers[lesson.tier] = { name: lesson.tierName, lessons: [] };
    }
    tiers[lesson.tier].lessons.push(lesson);
  }
  return tiers;
}

export function getMaxTier() {
  return Math.max(...LESSONS.map(l => l.tier));
}
